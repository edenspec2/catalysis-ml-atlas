function addSim(source, target, score, reason) {
  if (!graph.nodes.some(n => n.id === source) || !graph.nodes.some(n => n.id === target)) return;
  const e = {source, target, relation: 'paper_similarity', score, reason, density: score >= 7 ? 'sparse' : 'normal'};
  if (!sims.has(simKey(e))) {
    graph.paper_similarity_edges.push(e);
    sims.add(simKey(e));
  }
}
for (const row of EXTRA_SIM) addSim(...row);

