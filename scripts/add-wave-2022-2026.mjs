function journal(name) {
  name = String(name || '').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
  return JOURNAL[name] || name.replace(/Angewandte Chemie International Edition.*/i, 'Angew. Chem. Int. Ed.');
}

